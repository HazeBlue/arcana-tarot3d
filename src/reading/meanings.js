/**
 * 把问题类别键映射到具体配置，未知类别回落到综合。
 * @param {string} key 类别键
 * @returns {object} 类别配置
 */
export function getCategory(key) {
  // 命中则返回，否则返回综合配置
  return CATEGORIES[key] || CATEGORIES.general;
}

/**
 * 取元素透镜句子。
 * @param {string} element 元素名
 * @param {string} categoryKey 类别键
 * @param {Function} random 随机数函数
 * @returns {string} 洞察句
 */
export function pickElementLens(element, categoryKey, random) {
  // 取出该元素下的全部类别
  const byElement = ELEMENT_LENS[element] || ELEMENT_LENS['风'];
  // 取出该类别的候选句
  const list = byElement[categoryKey] || byElement.general || [];
  // 空列表时返回空串
  if (!list.length) return '';
  // 随机挑一句
  return list[Math.floor(random() * list.length)];
}
